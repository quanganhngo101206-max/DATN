SELECT TableName, RecordCount FROM (
    SELECT 'Account'               AS TableName, COUNT(*) AS RecordCount FROM Account        UNION ALL
    SELECT 'Staff',                COUNT(*) FROM Staff                                        UNION ALL
    SELECT 'Customer',             COUNT(*) FROM Customer                                     UNION ALL
    SELECT 'Provinces',            COUNT(*) FROM Provinces                                    UNION ALL
    SELECT 'Wards',                COUNT(*) FROM Wards                                        UNION ALL
    SELECT 'Address_shipping',     COUNT(*) FROM Address_shipping                             UNION ALL
    SELECT 'Product',              COUNT(*) FROM Product                                      UNION ALL
    SELECT 'Product_detail',       COUNT(*) FROM Product_detail                               UNION ALL
    SELECT 'Bill',                 COUNT(*) FROM Bill                                         UNION ALL
    SELECT 'Import_order',         COUNT(*) FROM Import_order                                 UNION ALL
    SELECT 'Import_order_detail',  COUNT(*) FROM Import_order_detail                         UNION ALL
    SELECT 'Discount_code',        COUNT(*) FROM Discount_code                               UNION ALL
    SELECT 'Review',               COUNT(*) FROM Review                                       UNION ALL
    SELECT 'Wishlist',             COUNT(*) FROM Wishlist
) t ORDER BY TableName


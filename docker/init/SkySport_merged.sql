-- ============================================
-- 1. TẠO BẢNG
-- ============================================
-- GHI CHÚ SỬA LỖI (so với bản gốc):
-- 1. Account: thêm UNIQUE (username), UNIQUE (email)
-- 2. Discount_code: thêm UNIQUE (code)
-- 3. Product_detail: thêm UNIQUE (product_id, size_id, color_id) + UNIQUE INDEX barcode
-- 4. Đổi toàn bộ cột tiền tệ từ FLOAT -> DECIMAL(18,2) / DECIMAL(5,2)
-- 5. [MỚI 01/07/2025] Bỏ bảng Districts, Wards liên kết trực tiếp với Provinces
--    Address_shipping bỏ cột district_id
-- ============================================

-- 1. Role
CREATE TABLE Role (
    id          INT PRIMARY KEY IDENTITY(1,1),
    name        NVARCHAR(50),
    create_date DATETIME,
    update_date DATETIME
)

-- 2. Brand
CREATE TABLE Brand (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(100),
    status      INT,
    delete_flag BIT,
    created_by  INT,
    updated_by  INT,
)

-- 3. Category
CREATE TABLE Category (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(100),
    status      INT,
    delete_flag BIT,
    created_by  INT,
    updated_by  INT,
)

-- 4. Material
CREATE TABLE Material (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(100),
    status      INT,
    delete_flag BIT,
    created_by  INT,
    updated_by  INT,
)

-- 5. Size
CREATE TABLE Size (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(50),
    delete_flag BIT
)

-- 6. Color
CREATE TABLE Color (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(50),
    delete_flag BIT
)

-- 7. Payment
CREATE TABLE Payment (
    id     INT PRIMARY KEY IDENTITY(1,1),
    name   NVARCHAR(100),
    status INT
)

-- 8. Account
CREATE TABLE Account (
    id            INT PRIMARY KEY IDENTITY(1,1),
    code          NVARCHAR(50),
    username      NVARCHAR(50),
    pass_word     NVARCHAR(255),
    email         NVARCHAR(100),
    birth_day     DATETIME,
    is_non_locked BIT,
    status        INT,
    role_id       INT FOREIGN KEY REFERENCES Role(id),
    create_date   DATETIME,
    update_date   DATETIME,
    created_by    INT,
    updated_by    INT,
    failed_attempts INT NULL,
    CONSTRAINT UQ_Account_Username UNIQUE (username),
    CONSTRAINT UQ_Account_Email    UNIQUE (email)
)

-- 9. Supplier
CREATE TABLE Supplier (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(100),
    phone       NVARCHAR(20),
    email       NVARCHAR(100),
    address     NVARCHAR(255),
    status      INT,
    delete_flag BIT DEFAULT 0,
    created_by  INT,
    updated_by  INT,
)

-- 10. Staff
CREATE TABLE Staff (
    id           INT PRIMARY KEY IDENTITY(1,1),
    code         NVARCHAR(50),
    name         NVARCHAR(100),
    phone_number NVARCHAR(20),
    email        NVARCHAR(100),
    gender       BIT,
    address      NVARCHAR(255),
    status       INT,
    account_id   INT FOREIGN KEY REFERENCES Account(id),
    created_by   INT,
    updated_by   INT,
    CONSTRAINT UQ_Staff_Account UNIQUE (account_id)
)

-- 11. Customer
CREATE TABLE Customer (
    id                  INT PRIMARY KEY IDENTITY(1,1),
    code                NVARCHAR(50),
    name                NVARCHAR(100),
    email               NVARCHAR(100),
    phone               NVARCHAR(20),
    account_id          INT FOREIGN KEY REFERENCES Account(id),
    address_shipping_id INT,
    created_by          INT,
    updated_by          INT,
    CONSTRAINT UQ_Customer_Account UNIQUE (account_id)
)

-- ============================================
-- 12. Địa chỉ hành chính (cấu trúc mới 01/07/2025)
--     Chỉ còn 2 cấp: Tỉnh/Thành → Phường/Xã
--     Bảng Districts đã bị bãi bỏ
-- ============================================
CREATE TABLE Provinces (
    id   INT PRIMARY KEY,
    name NVARCHAR(100) NOT NULL
)

CREATE TABLE Wards (
    id          INT PRIMARY KEY IDENTITY(1,1),
    name        NVARCHAR(100) NOT NULL,
    ward_code   NVARCHAR(20),              -- mã gốc 5 chữ số để tra cứu
    province_id INT NOT NULL FOREIGN KEY REFERENCES Provinces(id)
)

CREATE TABLE Address_shipping (
    id             INT PRIMARY KEY IDENTITY(1,1),
    address        NVARCHAR(255),
    receiver_name  NVARCHAR(100),
    receiver_phone NVARCHAR(20),
    is_default     BIT DEFAULT 0,
    customer_id    INT FOREIGN KEY REFERENCES Customer(id) ON DELETE CASCADE,
    province_id    INT NOT NULL DEFAULT 0,
    ward_id        INT NOT NULL DEFAULT 0
)

-- Khóa ngoại vòng tròn Customer ↔ Address_shipping
ALTER TABLE Customer ADD CONSTRAINT FK_Customer_AddressShipping
    FOREIGN KEY (address_shipping_id) REFERENCES Address_shipping(id)

-- 13. Product
CREATE TABLE Product (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    name        NVARCHAR(100),
    gender      INT,
    describe    NVARCHAR(MAX),
    status      INT,
    delete_flag BIT,
    category_id INT FOREIGN KEY REFERENCES Category(id),
    brand_id    INT FOREIGN KEY REFERENCES Brand(id),
    material_id INT FOREIGN KEY REFERENCES Material(id),
    create_date DATETIME,
    update_date DATETIME,
    created_by  INT,
    updated_by  INT,
)

-- 14. Image
CREATE TABLE Image (
    id          INT PRIMARY KEY IDENTITY(1,1),
    name        NVARCHAR(100),
    link        NVARCHAR(255),
    file_type   NVARCHAR(50),
    product_id  INT FOREIGN KEY REFERENCES Product(id) ON DELETE CASCADE,
    create_date DATETIME,
    update_date DATETIME
)

-- 15. Product_discount
CREATE TABLE Product_discount (
    id                INT PRIMARY KEY IDENTITY(1,1),
    discount_amount   DECIMAL(18,2),
    start_date        DATETIME,
    end_date          DATETIME,
    [close]           BIT,
    product_detail_id INT,
    created_by        INT,
    updated_by        INT,
)

-- 16. Product_detail
CREATE TABLE Product_detail (
    id                  INT PRIMARY KEY IDENTITY(1,1),
    barcode             NVARCHAR(100),
    price               DECIMAL(18,2),
    quantity            INT,
    delete_flag         BIT,
    product_id          INT FOREIGN KEY REFERENCES Product(id) ON DELETE CASCADE,
    size_id             INT FOREIGN KEY REFERENCES Size(id),
    color_id            INT FOREIGN KEY REFERENCES Color(id),
    product_discount_id INT FOREIGN KEY REFERENCES Product_discount(id),
    created_by          INT,
    updated_by          INT,
    CONSTRAINT UQ_ProductDetail_Variant UNIQUE (product_id, size_id, color_id)
)

CREATE UNIQUE INDEX UQ_ProductDetail_Barcode ON Product_detail(barcode) WHERE barcode IS NOT NULL

ALTER TABLE Product_discount ADD CONSTRAINT FK_ProductDiscount_ProductDetail
    FOREIGN KEY (product_detail_id) REFERENCES Product_detail(id)

-- 17. Discount_code
CREATE TABLE Discount_code (
    id                     INT PRIMARY KEY IDENTITY(1,1),
    code                   NVARCHAR(50),
    detail                 NVARCHAR(255),
    type                   INT,
    discount_amount        DECIMAL(18,2),
    percentage             DECIMAL(5,2),
    minimum_amount_in_cart DECIMAL(18,2),
    maximum_amount         DECIMAL(18,2),
    maximum_usage          INT,
    used_count             INT DEFAULT 0,
    start_date             DATETIME,
    end_date               DATETIME,
    status                 INT,
    delete_flag            BIT,
    created_by             INT,
    updated_by             INT,
    CONSTRAINT UQ_DiscountCode_Code UNIQUE (code)
)

-- 18. Cart
CREATE TABLE Cart (
    id          INT PRIMARY KEY IDENTITY(1,1),
    customer_id INT FOREIGN KEY REFERENCES Customer(id) ON DELETE CASCADE,
    account_id  INT FOREIGN KEY REFERENCES Account(id),
    create_date DATETIME,
    update_date DATETIME,
    created_by  INT,
    updated_by  INT,
)

-- 19. Cart_detail
CREATE TABLE Cart_detail (
    id                INT PRIMARY KEY IDENTITY(1,1),
    quantity          INT,
    cart_id           INT FOREIGN KEY REFERENCES Cart(id) ON DELETE CASCADE,
    product_detail_id INT FOREIGN KEY REFERENCES Product_detail(id),
    created_by        INT,
    updated_by        INT,
)

-- 20. Bill
CREATE TABLE Bill (
    id               INT PRIMARY KEY IDENTITY(1,1),
    code             NVARCHAR(50),
    note             NVARCHAR(500),
    invoice_type     INT,
    billing_address  NVARCHAR(255),
    subtotal         DECIMAL(18,2),
    shipping_fee     DECIMAL(18,2),
    promotion_price  DECIMAL(18,2),
    amount           DECIMAL(18,2),
    status           INT,
    return_status    INT,
    discount_code_id INT FOREIGN KEY REFERENCES Discount_code(id),
    customer_id      INT FOREIGN KEY REFERENCES Customer(id),
    payment_id       INT FOREIGN KEY REFERENCES Payment(id),
    create_date      DATETIME,
    update_date      DATETIME,
    created_by       INT,
    updated_by       INT,
)

-- 21. Bill_detail
CREATE TABLE Bill_detail (
    id                INT PRIMARY KEY IDENTITY(1,1),
    moment_price      DECIMAL(18,2),
    quantity          INT,
    return_quantity   INT DEFAULT 0,
    bill_id           INT FOREIGN KEY REFERENCES Bill(id) ON DELETE CASCADE,
    product_detail_id INT FOREIGN KEY REFERENCES Product_detail(id),
    created_by        INT,
    updated_by        INT,
)

-- 22. Order_status_history
CREATE TABLE Order_status_history (
    id           INT PRIMARY KEY IDENTITY(1,1),
    status       INT,
    note         NVARCHAR(255),
    created_date DATETIME,
    bill_id      INT FOREIGN KEY REFERENCES Bill(id) ON DELETE CASCADE,
    staff_id     INT FOREIGN KEY REFERENCES Staff(id)
)

-- 23. Return_request
CREATE TABLE Return_request (
    id          INT PRIMARY KEY IDENTITY(1,1),
    code        NVARCHAR(50),
    status      INT,
    bill_id     INT FOREIGN KEY REFERENCES Bill(id) ON DELETE CASCADE,
    create_date DATETIME,
    created_by  INT,
    updated_by  INT,
)

-- 24. Return_request_detail
CREATE TABLE Return_request_detail (
    id                  INT PRIMARY KEY IDENTITY(1,1),
    quantity_return     INT,
    moment_price_refund DECIMAL(18,2),
    return_id           INT FOREIGN KEY REFERENCES Return_request(id) ON DELETE CASCADE,
    product_detail_id   INT FOREIGN KEY REFERENCES Product_detail(id),
    created_by          INT,
    updated_by          INT,
)

-- 25. Bill_return
CREATE TABLE Bill_return (
    id                   INT PRIMARY KEY IDENTITY(1,1),
    code                 NVARCHAR(50),
    return_reason        NVARCHAR(255),
    return_detail        NVARCHAR(255),
    return_date          DATETIME,
    percent_fee_exchange DECIMAL(5,2),
    return_money         DECIMAL(18,2),
    is_cancel            BIT,
    return_status        INT,
    bill_id              INT FOREIGN KEY REFERENCES Bill(id),
    return_request_id    INT FOREIGN KEY REFERENCES Return_request(id),
    created_by           INT,
    updated_by           INT,
)

-- 26. Import_order
CREATE TABLE Import_order (
    id           INT PRIMARY KEY IDENTITY(1,1),
    code         NVARCHAR(50),
    total_amount DECIMAL(18,2),
    status       INT,
    note         NVARCHAR(255),
    staff_id     INT FOREIGN KEY REFERENCES Staff(id),
    supplier_id  INT FOREIGN KEY REFERENCES Supplier(id),
    create_date  DATETIME,
    update_date  DATETIME,
    created_by   INT,
    updated_by   INT,
)

-- 27. Import_order_detail
CREATE TABLE Import_order_detail (
    id                INT PRIMARY KEY IDENTITY(1,1),
    quantity          INT,
    import_price      DECIMAL(18,2),
    import_order_id   INT FOREIGN KEY REFERENCES Import_order(id) ON DELETE CASCADE,
    product_detail_id INT FOREIGN KEY REFERENCES Product_detail(id),
    created_by        INT,
    updated_by        INT,
)

-- 28. Review
CREATE TABLE Review (
    id          INT PRIMARY KEY IDENTITY(1,1),
    rating      INT NOT NULL,
    comment     NVARCHAR(MAX),
    customer_id INT NOT NULL FOREIGN KEY REFERENCES Customer(id) ON DELETE CASCADE,
    product_id  INT NOT NULL FOREIGN KEY REFERENCES Product(id),
    create_date DATETIME DEFAULT GETDATE(),
    created_by  INT,
    updated_by  INT,
)

-- 29. Wishlist
CREATE TABLE Wishlist (
    id          INT PRIMARY KEY IDENTITY(1,1),
    customer_id INT NOT NULL FOREIGN KEY REFERENCES Customer(id) ON DELETE CASCADE,
    created_by  INT,
    updated_by  INT,
)

-- 30. Wishlist_detail
CREATE TABLE Wishlist_detail (
    id          INT PRIMARY KEY IDENTITY(1,1),
    wishlist_id INT NOT NULL FOREIGN KEY REFERENCES Wishlist(id) ON DELETE CASCADE,
    product_id  INT NOT NULL FOREIGN KEY REFERENCES Product(id),
    created_by  INT,
    updated_by  INT,
)

